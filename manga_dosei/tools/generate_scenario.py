def _format_target_date_jp(target_date: str) -> str:
    if len(target_date) != 8 or not target_date.isdigit():
        return target_date
    return f"{target_date[:4]}年{target_date[4:6]}月{target_date[6:8]}日"


def _build_prompt(news_text: str, target_date: str) -> str:
    target_date_jp = _format_target_date_jp(target_date)
    return f"""
{news_text}

上記が「漫画にする首相動静」です。これを漫画の1ページとした台本を、以下の「要件」と「台本例」にならって作成してください。

【対象日】
- target_date: {target_date} (= {target_date_jp})
- 台本のタイトル冒頭の日付には **必ず {target_date_jp} を使用** すること。
  前日や別の日に置き換えない。

【重要】入力文中の「## 参照した関連ニュース」に記載されていない関連ニュース、
配信日が不明な関連ニュース、対象日より後に配信された関連ニュースは
台本に使用しないでください。

{_SCENARIO_REQUIREMENTS}

応答フォーマット (output_schema):
- 台本生成に成功した場合: body に台本本文
  （余分なヘッダー・フッター・説明文は含めない）。error は空文字。
- 生成できなかった場合: body は空文字、error に理由を記載。
""".strip()


def _build_instruction(context: ReadonlyContext) -> str:
    news_text = context.state.get("temp:news_text", "")
    target_date = context.state.get("temp:target_date", "")
    return _build_prompt(news_text, target_date)


async def _before(callback_context: CallbackContext):
    return await prepare_step(
        callback_context,
        step=_STEP,
        required_artifacts=_REQUIRED,
        load_prior={"temp:news_text": "news.md"},
    )


async def _after(callback_context: CallbackContext):
    return await save_step_output(
        callback_context,
        step=_STEP,
        output_key=_OUTPUT_KEY,
        artifact_name=_ARTIFACT,
    )


_agent = LlmAgent(
    name=_STEP,
    model=DEFAULT_TEXT_MODEL,
    description=_DESCRIPTION,
    instruction=_build_instruction,
    input_schema=StepInput,
    output_schema=StepOutput,
    output_key=_OUTPUT_KEY,
    before_agent_callback=_before,
    after_agent_callback=_after,
)


generate_scenario_tool = AgentTool(agent=_agent)
